// Writes licenses/THIRD-PARTY.txt from package-lock.json: every package that ships to production (not dev-only),
// with its licence read from node_modules. Run `npm run licenses` after changing dependencies.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const rows = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path || info.dev) continue;
  const name = path.split("node_modules/").pop();
  const manifest = `${path}/package.json`;
  const license = existsSync(manifest)
    ? (JSON.parse(readFileSync(manifest, "utf8")).license ?? "UNKNOWN")
    : (info.license ?? "NOT INSTALLED ON THIS OS");
  rows.push({ name, version: info.version, license: String(license.type ?? license) });
}
rows.sort((a, b) => a.name.localeCompare(b.name));

const counts = {};
for (const r of rows) counts[r.license] = (counts[r.license] ?? 0) + 1;
const summary = Object.entries(counts)
  .sort((a, b) => b[1] - a[1])
  .map(([l, n]) => `  ${String(n).padStart(3)}  ${l}`)
  .join("\n");
const list = rows.map((r) => `${r.name}@${r.version}  ${r.license}`).join("\n");
writeFileSync(
  "licenses/THIRD-PARTY.txt",
  `Third-party packages that ship with the production build (${rows.length}).\nGenerated by scripts/licenses.mjs from package-lock.json.\n\nLicence summary\n${summary}\n\nPackages\n${list}\n`,
);
console.log(`${rows.length} packages\n${summary}`);
